import {Pool} from 'pg'
import env from '../config/env'


// Connection Pool (фундаментальное понятие БД-клиентов в Node.js):
// Открытие TCP-соединения к Postgres стоит ~5–50ms (TCP handshake + Postgres auth).
// На каждый HTTP-запрос открывать новое соединение — катастрофа по латентности.
// Решение: держать пул заранее открытых соединений и переиспользовать их.
//
// Внутри pg-библиотеки `Pool`:
//   - При первом `pool.query()` создаёт N соединений (по умолчанию max=10).
//   - Запросы стоят в очереди, пока соединение не освободится.
//   - Idle-соединения держатся открытыми и переиспользуются.
//   - При ошибке соединение выбрасывается из пула, заводится новое.
//
// Альтернатива — `new Client()` (одно соединение): подходит для CLI/миграций, НЕ для HTTP-сервера.
//
// FLAG: настройки пула не заданы — используются дефолты pg (max: 10, idleTimeoutMillis: 10000).
// Для production стоит задавать явно (max в зависимости от Postgres `max_connections` / количества
// инстансов API; idleTimeout под нагрузочный профиль). Сейчас "по умолчанию" — это магия.
//
// FLAG: модуль создаёт `pool` на верхнем уровне (module-level side effect). Это значит,
// `import` этого файла = создание пула. Затрудняет тестирование (нельзя получить инстанс
// без побочного эффекта). Альтернатива: фабрика `createPool(env)`, вызываемая из Composition Root.
export const pool = new Pool({connectionString: env.databaseUrl})

// pool.on('error', ...) — ловит ошибки на ИДЛ-соединениях (когда никто не делает query,
// но связь оборвалась). Без этого обработчика Node бросает unhandledError и роняет процесс.
// Это распространённая ловушка в pg.
//
// JSON-логирование (`JSON.stringify({...})`) — структурированные логи для агрегаторов
// (Loki, Datadog, CloudWatch). Альтернатива `console.error('pg error:', err)` — текстовая
// строка, которую агрегатор не сможет разобрать на поля.
//
// FLAG: ad-hoc логгер вместо нормального (pino/winston). Цена: нет уровней, нет ротации,
// нет контекста (request-id). Польза: ноль зависимостей. Для прода — недостаточно.
pool.on('error', (err) => {
	console.error(JSON.stringify({level: 'error', msg: 'pg pool error', error: err.message, ts: new Date().toISOString()}))
})
